const seedMenu = async () => {
  // Branches
  const branchDocs = {};
  for (const b of branchesData) {
    const branch = await Branch.findOneAndUpdate(
      { name: b.name },
      { $setOnInsert: b },
      { upsert: true, new: true }
    );
    branchDocs[b.name] = branch;
  }

  // Categories + Products
  let createdProducts = 0;
  for (const cat of categoriesData) {
    const category = await Category.findOneAndUpdate(
      { name: cat.name },
      { $setOnInsert: { name: cat.name } },
      { upsert: true, new: true }
    );

    for (const [name, price, unit] of cat.products) {
      const result = await Product.updateOne(
        { name, categoryId: category._id },
        { $setOnInsert: { name, categoryId: category._id, price, unit } },
        { upsert: true }
      );
      if (result.upsertedCount > 0) createdProducts += 1;
    }
  }

  console.log(
    `Menu seeded: ${branchesData.length} branches, ${categoriesData.length} categories, ${createdProducts} new products`
  );
};

export default seedMenu;
